def main() -> None:
    data = {
        "repos": "--",
        "followers": "--",
        "following": "--",
        "updated": "unknown",
        "stars": "--",
    }
    try:
        fetched = fetch_user_data()
        fetched["stars"] = count_repo_stars()
        data = fetched
    except Exception:
        pass

    OUTPUT_PATH.write_text(build_card(data), encoding="utf-8")


if __name__ == "__main__":
    main()
