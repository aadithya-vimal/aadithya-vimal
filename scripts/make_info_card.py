from __future__ import annotations

import json
import urllib.request
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = ROOT / "assets" / "info-card.svg"
USERNAME = "aadithya-vimal"


def fetch_user_data() -> dict[str, str | int]:
    url = f"https://api.github.com/users/{USERNAME}"
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "aadithya-vimal-profile-art",
        },
    )
    with urllib.request.urlopen(request, timeout=20) as response:
        payload = json.loads(response.read().decode("utf-8"))

    repos = int(payload.get("public_repos", 0))
    followers = int(payload.get("followers", 0))
    following = int(payload.get("following", 0))
    updated = payload.get("updated_at", "")
    updated_label = "unknown"
    if updated:
        updated_label = datetime.fromisoformat(updated.replace("Z", "+00:00")).strftime("%d %b %Y")
    return {
        "repos": repos,
        "followers": followers,
        "following": following,
        "updated": updated_label,
    }


def count_repo_stars() -> int:
    page = 1
    stars = 0
    while True:
        url = f"https://api.github.com/users/{USERNAME}/repos?per_page=100&page={page}"
        request = urllib.request.Request(
            url,
            headers={
                "Accept": "application/vnd.github+json",
                "User-Agent": "aadithya-vimal-profile-art",
            },
        )
        with urllib.request.urlopen(request, timeout=20) as response:
            repos = json.loads(response.read().decode("utf-8"))
        if not repos:
            break
        stars += sum(int(repo.get("stargazers_count", 0)) for repo in repos)
        page += 1
    return stars


